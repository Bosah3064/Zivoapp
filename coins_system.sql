-- RLS for Settings (Only Admin can modify, everyone can read)
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Everyone can read settings" ON public.settings FOR SELECT USING (true);
CREATE POLICY "Only admins can update settings" ON public.settings FOR UPDATE USING (
  EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND is_admin = true)
);

-- 3. Transactions Table
CREATE TABLE IF NOT EXISTS public.transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  amount INTEGER NOT NULL,
  type TEXT CHECK (type IN ('purchase', 'reward', 'spend', 'referral')) NOT NULL,
  details TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- RLS for Transactions
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
DO $$ 
BEGIN 
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Users can see own transactions') THEN
        CREATE POLICY "Users can see own transactions" ON public.transactions FOR SELECT USING (auth.uid() = user_id);
    END IF;
END $$;

-- 3. Function to Claim Daily Reward
CREATE OR REPLACE FUNCTION claim_daily_reward(target_user_id UUID)
RETURNS JSON AS $$
DECLARE
    reward_amount INTEGER := 50;
    last_claim TIMESTAMP WITH TIME ZONE;
BEGIN
    SELECT last_reward_claim INTO last_claim FROM public.profiles WHERE id = target_user_id;

    IF last_claim IS NOT NULL AND last_claim > (NOW() - INTERVAL '24 hours') THEN
        RETURN json_build_object('success', false, 'message', 'Already claimed today');
    END IF;

    UPDATE public.profiles
    SET coins = coins + reward_amount,
        last_reward_claim = NOW()
    WHERE id = target_user_id;

    INSERT INTO public.transactions (user_id, amount, type, details)
    VALUES (target_user_id, reward_amount, 'reward', 'Daily login reward');

    RETURN json_build_object('success', true, 'amount', reward_amount);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 4. Function to Spend Coins
CREATE OR REPLACE FUNCTION spend_coins(target_user_id UUID, spend_amount INTEGER, spend_details TEXT)
RETURNS JSON AS $$
DECLARE
    current_coins INTEGER;
BEGIN
    SELECT coins INTO current_coins FROM public.profiles WHERE id = target_user_id;

    IF current_coins < spend_amount THEN
        RETURN json_build_object('success', false, 'message', 'Insufficient coins');
    END IF;

    UPDATE public.profiles
    SET coins = coins - spend_amount
    WHERE id = target_user_id;

    INSERT INTO public.transactions (user_id, amount, type, details)
    VALUES (target_user_id, -spend_amount, 'spend', spend_details);

    RETURN json_build_object('success', true, 'remaining', current_coins - spend_amount);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 5. handle_call_billing (Caller to Receiver transfer)
-- Updated: Default reward_percent is now 10
CREATE OR REPLACE FUNCTION handle_call_billing(
    caller_id UUID, 
    receiver_id UUID, 
    cost_amount INTEGER, 
    reward_percent INTEGER DEFAULT 10
)
RETURNS JSON AS $$
DECLARE
    caller_coins INTEGER;
    reward_amount INTEGER;
BEGIN
    SELECT coins INTO caller_coins FROM public.profiles WHERE id = caller_id;
    IF caller_coins < cost_amount THEN
        RETURN json_build_object('success', false, 'message', 'Insufficient coins');
    END IF;

    UPDATE public.profiles SET coins = coins - cost_amount WHERE id = caller_id;
    INSERT INTO public.transactions (user_id, amount, type, details)
    VALUES (caller_id, -cost_amount, 'spend', 'Video call cost');

    reward_amount := (cost_amount * reward_percent) / 100;
    UPDATE public.profiles SET coins = coins + reward_amount WHERE id = receiver_id;
    INSERT INTO public.transactions (user_id, amount, type, details)
    VALUES (receiver_id, reward_amount, 'reward', 'Video call received reward');

    RETURN json_build_object('success', true, 'caller_remaining', caller_coins - cost_amount);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
