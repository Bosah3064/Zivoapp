-- Enable PostGIS for location-based matching
CREATE EXTENSION IF NOT EXISTS postgis;

-- 1. PROFILES TABLE
-- Extends the built-in auth.users table
CREATE TABLE public.profiles (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  full_name TEXT,
  age INTEGER,
  gender TEXT, -- 'male', 'female', 'other'
  bio TEXT,
  interests TEXT[], -- Array of strings e.g., ['travel', 'music', 'coding']
  intent TEXT, -- 'dating', 'friendship', 'networking'
  photos TEXT[], -- Array of photo URLs
  video_url TEXT, -- Optional intro video
  is_verified BOOLEAN DEFAULT FALSE,
  location GEOGRAPHY(POINT), -- PostGIS Point for distance calculation
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. SWIPES TABLE
-- Tracks likes and dislikes
CREATE TABLE public.swipes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  swiper_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  swiped_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  type TEXT CHECK (type IN ('like', 'dislike')) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  UNIQUE(swiper_id, swiped_id)
);

-- 3. MATCHES TABLE
-- Created automatically when a mutual 'like' occurs
CREATE TABLE public.matches (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_1 UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  user_2 UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  UNIQUE(user_1, user_2)
);

-- 4. MESSAGES TABLE
CREATE TABLE public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id UUID REFERENCES public.matches(id) ON DELETE CASCADE NOT NULL,
  sender_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  content TEXT NOT NULL,
  type TEXT DEFAULT 'text' CHECK (type IN ('text', 'image', 'video')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. BLOCKS & REPORTS (Safety Features)
CREATE TABLE public.safety_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  reported_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  reason TEXT NOT NULL,
  details TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- TRIGGERS & FUNCTIONS

-- Function to handle mutual matches
CREATE OR REPLACE FUNCTION handle_swipe_match()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.type = 'like' THEN
    -- Check if the other user has already liked this swiper
    IF EXISTS (
      SELECT 1 FROM public.swipes 
      WHERE swiper_id = NEW.swiped_id 
      AND swiped_id = NEW.swiper_id 
      AND type = 'like'
    ) THEN
      -- Create a mutual match
      INSERT INTO public.matches (user_1, user_2)
      VALUES (
        LEAST(NEW.swiper_id, NEW.swiped_id),
        GREATEST(NEW.swiper_id, NEW.swiped_id)
      )
      ON CONFLICT DO NOTHING;
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger to create match on like
CREATE TRIGGER on_swipe_like
AFTER INSERT ON public.swipes
FOR EACH ROW
EXECUTE FUNCTION handle_swipe_match();

-- Automatically create profile on signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, photos)
  VALUES (NEW.id, NEW.raw_user_meta_data->>'full_name', ARRAY[]::TEXT[]);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ROW LEVEL SECURITY (RLS) policies
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.swipes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

-- Profile Policies: Everyone can read others (to swipe), but only users can update their own
CREATE POLICY "Public profiles are viewable by everyone" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Users can update own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- Swipe Policies: Users can only see/create their own swipes
CREATE POLICY "Users can see own swipes" ON public.swipes FOR SELECT USING (auth.uid() = swiper_id);
CREATE POLICY "Users can create own swipes" ON public.swipes FOR INSERT WITH CHECK (auth.uid() = swiper_id);

-- Match Policies: Users can only see matches they are part of
CREATE POLICY "Users can see own matches" ON public.matches FOR SELECT USING (auth.uid() = user_1 OR auth.uid() = user_2);

-- Message Policies: Users can only see/send messages in matches they belong to
CREATE POLICY "Users can see match messages" ON public.messages FOR SELECT USING (
  EXISTS (
    SELECT 1 FROM public.matches 
    WHERE id = match_id AND (user_1 = auth.uid() OR user_2 = auth.uid())
  )
);
CREATE POLICY "Users can send messages to own matches" ON public.messages FOR INSERT WITH CHECK (
  auth.uid() = sender_id AND
  EXISTS (
    SELECT 1 FROM public.matches 
    WHERE id = match_id AND (user_1 = auth.uid() OR user_2 = auth.uid())
  )
);
